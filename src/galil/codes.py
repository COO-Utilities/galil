class AxisStatus(IntFlag):
    """Axis status bits, as reported by TS"""

    LATCH_OCCURRED = 1 << 0
    HOME_SWITCH = 1 << 1
    # The limit switch bits are set when the switch is inactive
    REVERSE_LIMIT_INACTIVE = 1 << 2
    FORWARD_LIMIT_INACTIVE = 1 << 3
    MOTOR_OFF = 1 << 5
    ERROR_LIMIT_EXCEEDED = 1 << 6
    IN_MOTION = 1 << 7
